// ============================================================
// era-season-anchors.js —— 历史模式年度名单锚点（方案 A，结构兼容 B）
// 数据：每年每队 4-6 名首发级真实球员（B 升级只需在数组追加替补名字，引擎不变）
// 引擎：每个历史赛季开始前按锚定率把球员归位到真实球队；
//       玩家交易/招募的球员（在玩家球队内）优先于锚定归位，永不搬走。
// 加载位置：era-rosters.js 之后、主逻辑之前。
// ============================================================

var HISTORICAL_SEASON_ANCHORS = {};

/** 玩家交易/招募过的球员：永久跳过锚定归位（nameEN -> true） */
function markAnchorLocked(nameEN) {
  try {
    if (!nameEN) return;
    STATE.career = STATE.career || {};
    STATE.career.anchorLocked = STATE.career.anchorLocked || {};
    STATE.career.anchorLocked[nameEN] = true;
  } catch(e) {}
}
function isAnchorLocked(nameEN) {
  try {
    var c = STATE.career || {};
    return !!(c.anchorLocked && c.anchorLocked[nameEN]);
  } catch(e) { return false; }
}

/** 当前即将开始的历史赛季应套用的锚点年份（eraStart + 已完成赛季数） */
function getAnchorYear() {
  if (STATE.draftMode !== 'historical' || !STATE.eraStart) return null;
  var sc = (STATE.career && STATE.career.seasonCount) || 0;
  return String((parseInt(STATE.eraStart, 10) || 1984) + sc);
}

/** 按名字查找联盟内球员（nameEN/name/cname 三种键） */
var _anchorIdxCache = null;
var _anchorIdxSeason = null;
function findAnchorPlayer(nameKey) {
  if (!nameKey) return null;
  // ★ 性能优化：每赛季只建一次名字索引，避免每次全联盟遍历
  var _sig = STATE && STATE.career ? STATE.career.seasonCount : 0;
  if (_anchorIdxSeason !== _sig || !_anchorIdxCache) {
    _anchorIdxCache = {};
    _anchorIdxSeason = _sig;
    for (var _t in NBA2K_DATA) {
      var _r = NBA2K_DATA[_t];
      if (!Array.isArray(_r)) continue;
      for (var _i = 0; _i < _r.length; _i++) {
        var p = _r[_i];
        if (!p) continue;
        if (p.nameEN) _anchorIdxCache[p.nameEN] = p;
        if (p.name && p.name !== p.nameEN) _anchorIdxCache[p.name] = p;
        if (p.cname && p.cname !== p.nameEN && p.cname !== p.name) _anchorIdxCache[p.cname] = p;
      }
    }
  }
  return _anchorIdxCache[nameKey] || null;
}

/** 锚定率：星级(OVR>=88 或 tier=star) 85%，其余 60%（可被 game-config 覆盖） */
function isAnchorCore(p) {
  return !!(p && ((parseInt(p.ovr, 10) || 0) >= 85 || p._tier === 'star' || p._talent === 'star' || (parseInt(p._potential, 10) || 0) >= 92));
}
function getAnchorRate(p) {
  var core = isAnchorCore(p), base = core ? 0.98 : 0.72;
  try {
    var cfg = (typeof ANCHOR_CONFIG !== 'undefined') ? ANCHOR_CONFIG : null;
    if (cfg && typeof cfg.rate === 'number') base = cfg.rate;
    else if (cfg) { if (core && typeof cfg.starRate === 'number') base = cfg.starRate; if (!core && typeof cfg.roleRate === 'number') base = cfg.roleRate; }
  } catch(e) {}
  return base;
}

/** 把球员从当前球队移动到目标球队；目标满 14 人时替换最低 OVR 的可替换球员（非锚定/非锁定/非玩家队） */
function moveAnchorPlayer(p, targetTeam) {
  var srcTeam = null;
  for (var _t in NBA2K_DATA) {
    var _r = NBA2K_DATA[_t];
    if (!Array.isArray(_r)) continue;
    for (var _i = 0; _i < _r.length; _i++) {
      if (_r[_i] === p) { srcTeam = _t; _r.splice(_i, 1); break; }
    }
    if (srcTeam) break;
  }
  var target = NBA2K_DATA[targetTeam] || (NBA2K_DATA[targetTeam] = []);
  if (target.length >= 14) {
    var worst = null, worstIdx = -1;
    for (var _j = 0; _j < target.length; _j++) {
      var tp = target[_j];
      if (!tp || tp._isUser || isAnchorLocked(tp.nameEN || tp.name || '')) continue;
      if (tp._tier === 'star' || (parseInt(tp.ovr, 10) || 0) >= 88) continue;
      if (!worst || (parseInt(tp.ovr, 10) || 0) < (parseInt(worst.ovr, 10) || 0)) { worst = tp; worstIdx = _j; }
    }
    if (worstIdx < 0) { if (srcTeam) NBA2K_DATA[srcTeam].push(p); return false; }
    target.splice(worstIdx, 1); // 被挤出的球员进入自由市场池
    try {
      if (STATE._freeAgentPool && Array.isArray(STATE._freeAgentPool)) STATE._freeAgentPool.push(worst);
    } catch(e) {}
  }
  target.push(p);
  return true;
}

/** 本季已发生的交易/新签约是否豁免归位（保持交易与自由市场有操作感，历史锚点不覆盖） */
function isSeasonMoveExempt(p) {
  try {
    if (!p) return false;
    var sc = (STATE.career && STATE.career.seasonCount) || 0;
    if (p._justSignedSeason === sc) return true; // 本季新签约（含自由市场/巨星招募）
    var _lc = STATE._leagueChanges || {};
    var _nm = p.nameEN || p.name || '';
    var _cn = p.cname || '';
    var _trs = _lc.trades || [];
    for (var _ti = 0; _ti < _trs.length; _ti++) {
      var _tr = _trs[_ti];
      if (_tr.playerA === _nm || _tr.playerB === _nm || _tr.playerA === _cn || _tr.playerB === _cn) return true;
    }
  } catch(e) {}
  return false;
}

/** 套用指定年份锚点（默认取当前即将开始的赛季年份；respectSeasonMoves=true 时本季交易/新签约不归位） */
function applySeasonAnchors(year, respectSeasonMoves) {
  if (STATE.draftMode !== 'historical') return;
  year = year || getAnchorYear();
  if (!year) return;
  var anchors = HISTORICAL_SEASON_ANCHORS[year];
  if (!anchors) return;
  var locked = {};
  try { locked = (STATE.career && STATE.career.anchorLocked) || {}; } catch(e) {}
  var userTeam = STATE.careerTeam || null;
  var moved = 0, kept = 0;
  var teams = Object.keys(anchors);
  for (var _ti = 0; _ti < teams.length; _ti++) {
    var team = teams[_ti];
    var names = anchors[team] || [];
    for (var _ni = 0; _ni < names.length; _ni++) {
      try {
        var p = findAnchorPlayer(names[_ni]);
        if (!p) continue; // 未在联盟（退役/未入盟）：v1 不复活，留待 B 升级
        if (p._isUser) continue;
        if (locked[p.nameEN || p.name || '']) { kept++; continue; }
        // 玩家球队球员优先：玩家交易/招募来的球员不归位
        var curTeam = null;
        for (var _t in NBA2K_DATA) {
          if (Array.isArray(NBA2K_DATA[_t]) && NBA2K_DATA[_t].indexOf(p) >= 0) { curTeam = _t; break; }
        }
        if (curTeam === userTeam) { kept++; continue; }
        if (curTeam === team) { kept++; continue; } // 已在正确球队
        // Current-season moves remain visible for role players; NPC cores still return to their historical team.
        if (respectSeasonMoves && isSeasonMoveExempt(p) && !isAnchorCore(p)) { kept++; continue; }
        if (Math.random() >= getAnchorRate(p)) { kept++; continue; } // 波动：允许搅局
        if (moveAnchorPlayer(p, team)) moved++;
        else kept++;
      } catch(e) {}
    }
  }
  STATE._anchorStats = { year: year, moved: moved, kept: kept };
  return moved;
}

